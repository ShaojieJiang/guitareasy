// Copies the built player UI (mcp/app/dist) into ./public/mcp-app/ (not
// ./public/mcp/) so the static assets don't collide with the JSON-RPC
// endpoint at the exact path /mcp, and don't collide with the main
// GuitarEasy app's own /font/, /soundfont/, /assets/ paths when both share
// the guitareasy.app domain.
//
// Hashed files under assets/ are kept across syncs rather than wiped. ChatGPT
// snapshots the widget HTML for a resource URI, so a cached template can still
// reference a previous build's bundle; deleting it leaves the widget stuck on
// its loading placeholder. Content-hashed names make keeping them safe.
//
// A cached template would still run that build's UI, though. So every older
// entry bundle (assets/index-*.js) is rewritten into a small loader that
// swaps in the current build's stylesheet and entry; the asset server sends
// them with `max-age=0, must-revalidate`, so hosts pick up the loader.
//
// Also writes src/player-version.ts with a hash of the built index.html, so
// the widget's resource URI changes exactly when the player bundle does.
import { createHash } from 'node:crypto'
import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const sourceDir = path.resolve(here, '../../app/dist')
const targetDir = path.resolve(here, '../public/mcp-app')

await mkdir(targetDir, { recursive: true })
for (const entry of await readdir(targetDir)) {
  if (entry !== 'assets') await rm(path.join(targetDir, entry), { recursive: true, force: true })
}
await cp(sourceDir, targetDir, { recursive: true })
console.log(`Synced player assets into ${path.relative(process.cwd(), targetDir)}`)

const html = await readFile(path.join(targetDir, 'index.html'), 'utf8')

const entryUrl = html.match(/<script type="module"[^>]* src="([^"]+)"/)?.[1]
const stylesheetUrls = [...html.matchAll(/<link rel="stylesheet"[^>]* href="([^"]+)"/g)].map((match) => match[1])
if (!entryUrl) throw new Error('Could not find the player entry script in index.html')
const currentEntry = path.basename(new URL(entryUrl).pathname)
const loader = `// Superseded GuitarEasy player entry, rewritten by sync-player-assets.
// Hosts that cached older widget HTML still load this file; run the current build instead.
const current = ${JSON.stringify(stylesheetUrls)}
for (const link of document.querySelectorAll('link[rel="stylesheet"][href*="/mcp-app/assets/"]')) {
  if (!current.includes(link.href)) link.remove()
}
for (const href of current) {
  if ([...document.querySelectorAll('link[rel="stylesheet"]')].some((link) => link.href === href)) continue
  const link = document.createElement('link')
  link.rel = 'stylesheet'
  link.crossOrigin = ''
  link.href = href
  document.head.append(link)
}
import(${JSON.stringify(entryUrl)})
`
const assetsDir = path.join(targetDir, 'assets')
const superseded = (await readdir(assetsDir)).filter(
  (file) => /^index-[\w-]+\.js$/.test(file) && file !== currentEntry,
)
await Promise.all(superseded.map((file) => writeFile(path.join(assetsDir, file), loader)))
console.log(`Pointed ${superseded.length} superseded entry bundle(s) at ${currentEntry}`)

const bundleHash = createHash('sha256').update(html).digest('hex').slice(0, 12)
await writeFile(
  path.resolve(here, '../src/player-version.ts'),
  `// Generated by \`npm run sync-player-assets\`. Do not edit.\nexport const PLAYER_BUNDLE_HASH = '${bundleHash}'\n`,
)
console.log(`Player bundle hash: ${bundleHash}`)
